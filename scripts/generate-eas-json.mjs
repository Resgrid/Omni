#!/usr/bin/env node
// Generates apps/omni/eas.json: one profile per variant × build type (`unit-production`, `ic-internal`…)
// from Unit's profile set (omni-plan §6.2). EAS reads eas.json statically, so the file is generated and
// committed; CI fails if it is stale (`--check`). Run `pnpm eas:generate` after changing profiles or variants.
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const { VARIANT_IDS } = require('@resgrid/config-plugins');

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'apps', 'omni', 'eas.json');

const images = { ios: { image: 'latest' }, android: { image: 'latest' } };
const withEnv = (appEnv, extra = {}) => ({ EXPO_NO_DOTENV: '1', APP_ENV: appEnv, FLIPPER_DISABLE: '1', ...extra });

// Build types (key → profile body without APP_VARIANT). Channels map to expo-updates (D18).
const profiles = {
  production: { distribution: 'store', channel: 'production', ...images, envBase: 'production' },
  'production-aab': { distribution: 'store', channel: 'production', credentialsSource: 'local', ...images, envBase: 'production' },
  'production-apk': { distribution: 'store', channel: 'production', credentialsSource: 'local', ios: images.ios, android: { buildType: 'apk', image: 'latest' }, envBase: 'production' },
  staging: { channel: 'staging', ios: images.ios, android: { buildType: 'apk', image: 'latest' }, envBase: 'staging' },
  internal: { distribution: 'internal', channel: 'internal', ios: images.ios, android: { buildType: 'apk', image: 'latest' }, envBase: 'internal' },
  development: { developmentClient: true, distribution: 'internal', ios: images.ios, android: { buildType: 'apk', image: 'latest' }, envBase: 'development' },
  'dev-sim': { developmentClient: true, ios: { simulator: true, image: 'latest' }, android: { buildType: 'apk', image: 'latest' }, envBase: 'development' },
  simulator: { ios: { simulator: true, image: 'latest' }, android: { image: 'latest' }, envBase: 'development' },
};

const build = {};
const submit = {};
for (const variant of VARIANT_IDS) {
  for (const [name, { envBase, ...body }] of Object.entries(profiles)) {
    build[`${variant}-${name}`] = { ...body, node: '22.18.0', pnpm: '10.5.2', env: withEnv(envBase, { APP_VARIANT: variant }) };
  }
  submit[`${variant}-production`] = {};
}

const easJson = {
  $comment: 'Generated by scripts/generate-eas-json.mjs — do not edit by hand.',
  cli: { version: '>= 16.0.0', promptToConfigurePushNotifications: false, appVersionSource: 'local' },
  build,
  submit,
};

const output = JSON.stringify(easJson, null, 2) + '\n';
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current.replace(/\r\n/g, '\n') !== output) {
    console.error('apps/omni/eas.json is stale — run `pnpm eas:generate`.');
    process.exit(1);
  }
  console.log('apps/omni/eas.json is up to date.');
} else {
  fs.writeFileSync(target, output);
  console.log(`Wrote ${Object.keys(build).length} build profiles to apps/omni/eas.json`);
}
