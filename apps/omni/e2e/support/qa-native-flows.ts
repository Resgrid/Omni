import path from 'node:path';

import { persona, type QaDepartment, resolveRoute, signedInRoutes } from './qa-departments';
import { omniRoot, type VariantManifest } from './variants';

export type NativeFormFactor = 'phone' | 'tablet';

export interface NativeFlowOptions {
  app: VariantManifest;
  department: QaDepartment;
  formFactor: NativeFormFactor;
  platform: 'ios' | 'android';
  /** Where the flow file goes: the QA sub-flows are referenced relative to it. */
  flowDir: string;
}

const yaml = (value: string): string => JSON.stringify(value);

/** The permanent sidebar: its root id on Android, its profile name where only accessible elements are exposed (iOS). */
const SIDEBAR = 'shell-sidebar-permanent|shell-nav-profile-name';

/** `<app scheme>://<route>`: how a native build is told to open a screen (expo-router deep link). */
export const screenLink = (app: VariantManifest, route: string): string => `${app.identity.schemes[0]}://${route.replace(/^\//, '')}`;

/**
 * One department's Maestro flow for one native form factor: a clean launch with every permission granted, the
 * orientation (phones portrait, tablets landscape; on Android the run sets it on the emulator, because Maestro's
 * Android orientations assume a portrait-native screen and a Pixel Tablet's LANDSCAPE_LEFT is portrait), sign-in as
 * the department admin, a check that the form factor's layout engaged (Responder and Unit tablets in landscape show the
 * permanent sidebar; a phone never does), then every signed-in screen by deep link with a screenshot each. Null for a
 * department with no password sign-in (SSO only).
 */
export function nativeFlow({ app, department, formFactor, platform, flowDir }: NativeFlowOptions): string | null {
  if (!persona(department, 'admin') || department.features.sso === 'required') return null;
  const qaFlows = path.relative(flowDir, path.join(omniRoot, 'e2e', 'maestro', 'qa'));
  const permanent = formFactor === 'tablet' && app.shell.sidebar.tablet === 'permanent-landscape';

  const lines = [
    '# Generated by apps/omni/e2e/qa-regression.ts (support/qa-native-flows.ts) for one run; edit the generator, not this file.',
    'appId: ${APP_ID}',
    `name: ${yaml(`QA ${department.scenario} (${platform} ${formFactor})`)}`,
    'tags:',
    '  - qa',
    `  - ${formFactor}`,
    '---',
    `- runFlow: ${yaml(path.join(qaFlows, 'launch.yaml'))}`,
    ...(platform === 'ios' ? [`- setOrientation: ${formFactor === 'tablet' ? 'LANDSCAPE_LEFT' : 'PORTRAIT'}`] : []),
    `- runFlow: ${yaml(path.join(qaFlows, 'sign-in.yaml'))}`,
    // The sidebar is open without a tap only in the permanent layout; its profile name is an element iOS exposes too.
    permanent ? `- assertVisible:\n    id: ${yaml(SIDEBAR)}` : `- assertNotVisible:\n    id: ${yaml(SIDEBAR)}`,
  ];

  for (const pattern of signedInRoutes(app.id)) {
    const route = resolveRoute(pattern, department);

    if (!route.url) continue;
    const name = `${formFactor}-${route.url.replace(/^\//, '').replace(/[^a-zA-Z0-9]+/g, '-') || 'home'}`;

    lines.push(`- runFlow:\n    file: ${yaml(path.join(qaFlows, 'open-screen.yaml'))}\n    env:\n      SCREEN_URL: ${yaml(screenLink(app, route.url))}\n      SCREEN_NAME: ${yaml(name)}`);
  }

  return `${lines.join('\n')}\n`;
}
